import { recordCheck } from './native-evidence.mjs';
// Optional author acceptance of a generated starting point in an owned WebView2 fixture.
import assert from 'node:assert/strict';
import { realpath } from 'node:fs/promises';
import { isAbsolute, relative, resolve, sep, toNamespacedPath } from 'node:path';
import { DatabaseSync } from 'node:sqlite';

export async function qualifyReviewedSummaries({ page, data, output, createWritingProject, checks }) {
  const title = 'Accepted summary story';
  const prose = 'Mei left the silver key with Ren. He promised to guard the gate until she returned.';
  const summaryText = 'Ren holds the silver key and has promised to guard the gate for Mei.';
  await createWritingProject(title, 'chapter', 'The promise at the gate', prose);
  const library = await page.evaluate(() => window.__TAURI_INTERNALS__.invoke('library_snapshot'));
  const projectPath = await realpath(library.entries.find(entry => entry.title === title).path);
  const child = relative(toNamespacedPath(await realpath(data)), toNamespacedPath(projectPath));
  assert(child && !isAbsolute(child) && child !== '..' && !child.startsWith(`..${sep}`), 'Summary fixture must stay inside this synthetic run');
  const db = new DatabaseSync(resolve(projectPath, 'project.sqlite3'));
  const original = await page.evaluate(() => document.querySelector('.tiptap').editor.getJSON());
  const counts = () => ({ memory: db.prepare('SELECT count(*) AS n FROM memory_jobs').get().n, discussion: db.prepare('SELECT count(*) AS n FROM discussion_runs').get().n });
  try {
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await page.getByLabel('Maintenance provider', { exact: true }).selectOption('mock');
    await page.waitForFunction(async () => (await window.__TAURI_INTERNALS__.invoke('provider_state')).storyMemory.providerId === 'mock');
    await page.getByRole('button', { name: 'Close settings', exact: true }).click();
    await page.getByRole('button', { name: 'Story memory', exact: true }).click();
    await page.getByRole('button', { name: 'Refresh story memory', exact: true }).click();
    await page.getByRole('heading', { name: 'Current story memory', exact: true }).waitFor();
    const memoryDeadline = Date.now() + 10_000;
    const hasCompletedView = () => db.prepare("SELECT count(*) AS n FROM memory_views v JOIN memory_jobs j ON j.id=v.job_id WHERE j.status='completed'").get().n > 0;
    while (!hasCompletedView() && Date.now() < memoryDeadline) await new Promise(resolve => setTimeout(resolve, 50));
    assert(hasCompletedView(), 'The summary starting point needs a completed, persisted memory view');
    await page.getByRole('button', { name: 'Back to writing', exact: true }).click();
    const beforeReview = counts();
    await page.getByRole('button', { name: 'Story review', exact: true }).click();
    await page.getByRole('button', { name: 'Review saved chapter', exact: true }).click();
    await page.getByRole('button', { name: 'Use generated memory as a starting point', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#review-summary-text')?.value?.length > 0);
    assert.equal(db.prepare('SELECT count(*) AS n FROM ready_heads').get().n, 0, 'Copying generated text must not accept it');
    await page.getByLabel('Summary text', { exact: true }).fill(summaryText);
    await page.locator('#review-summary-audience').selectOption('reader');
    await page.getByRole('button', { name: 'Save reviewed details', exact: true }).click();
    await page.getByRole('button', { name: 'Mark this version reviewed', exact: true }).waitFor();
    assert.equal(db.prepare('SELECT count(*) AS n FROM ready_heads').get().n, 0, 'Staging must not accept a summary');
    await page.getByRole('button', { name: 'All projects', exact: true }).click();
    await page.getByRole('heading', { name: 'Your stories', exact: true }).waitFor();
    await page.getByRole('button', { name: /^Accepted summary story Last opened/ }).click();
    await page.getByRole('button', { name: 'Story review', exact: true }).click();
    await page.getByRole('button', { name: 'Resume saved review', exact: true }).click();
    assert.equal(await page.getByLabel('Summary text', { exact: true }).inputValue(), summaryText);
    await page.getByRole('button', { name: 'Mark this version reviewed', exact: true }).click();
    await page.getByRole('heading', { name: 'Reviewed version is current', exact: true }).waitFor();
    assert.deepEqual(counts(), beforeReview, 'Review/copy/reopen must not start AI work');
    assert.deepEqual(await page.evaluate(() => document.querySelector('.tiptap').editor.getJSON()), original);
    const bundle = db.prepare('SELECT b.* FROM ready_bundles b JOIN ready_heads h ON h.bundle_id=b.id').get();
    assert.equal(JSON.parse(bundle.summary_json).text, summaryText);
    await page.screenshot({ path: resolve(output, 'accepted-summary-reviewed.png') });
    await page.getByRole('button', { name: 'Back to writing', exact: true }).click();
    await page.getByRole('textbox', { name: 'Discuss this document', exact: true }).fill('What commitment should remain consistent?');
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    await page.locator('.persistent-feedback article').filter({ hasText: 'This test confirms discussion and context handling' }).waitFor();
    const inspector = page.locator('.context-inspector');
    if (await inspector.getAttribute('open') === null) await inspector.locator(':scope > summary').click();
    await inspector.getByText('Available', { exact: false }).first().waitFor();
    const available = inspector.locator(':scope > details').filter({ has: page.locator('summary').filter({ hasText: /^Available/ }) }).first();
    if (await available.getAttribute('open') === null) await available.locator(':scope > summary').click();
    await available.locator('.context-accepted-summary').waitFor();
    await available.locator('.context-accepted-summary > details > summary').click();
    await available.getByText(summaryText, { exact: true }).waitFor();
    const packet = JSON.parse(db.prepare('SELECT packet_json FROM context_packets ORDER BY rowid DESC LIMIT 1').get().packet_json);
    assert.deepEqual(packet.receipt.reviewedSummaries ?? [], []);
    assert.equal(packet.receipt.reviewedSummaryOmissions[0].reason, 'originalTextIncluded');
    await page.screenshot({ path: resolve(output, 'accepted-summary-context.png') });
    recordCheck(checks, 'native-reviewed-summaries:01', 'Native summary review explicitly copies current mock memory into an editable draft, stages and resumes it before acceptance, preserves prose without another AI request, and distinguishes accepted summary availability from full-text delivery');
    await page.getByRole('textbox', { name: 'Manuscript', exact: true }).fill('Ren returned the silver key to Mei before dusk.');
    await page.getByRole('status').filter({ hasText: /^Saved$/ }).waitFor();
    await page.getByRole('button', { name: 'Story review', exact: true }).click();
    await page.getByRole('button', { name: 'Clear summary', exact: true }).click();
    await page.getByRole('button', { name: /^Review (latest saved|saved) chapter$/ }).click();
    await page.getByRole('button', { name: 'Mark this version reviewed', exact: true }).click();
    await page.getByRole('heading', { name: 'Reviewed version is current', exact: true }).waitFor();
    const current = db.prepare('SELECT b.* FROM ready_bundles b JOIN ready_heads h ON h.bundle_id=b.id').get();
    assert.equal(current.summary_json, null);
    assert.deepEqual(db.prepare('SELECT * FROM ready_bundles WHERE id=?').get(bundle.id), bundle);
    assert.equal(counts().memory, beforeReview.memory);
    recordCheck(checks, 'native-reviewed-summaries:02', 'Native changed chapter review permits explicit summary clearing while retaining the earlier immutable accepted summary and avoiding automatic memory refresh');
    await page.getByRole('button', { name: 'All projects', exact: true }).click();
    await page.getByRole('heading', { name: 'Your stories', exact: true }).waitFor();
  } finally { db.close(); }
}
